const DEFAULT_LANGUAGE = 'uk';

function getStoredLanguage() {
  try {
    const saved = localStorage.getItem('fishing_game_lang');
    if (saved && I18N_MESSAGES[saved]) return saved;
  } catch (e) {
    // localStorage not accessible
  }
  return DEFAULT_LANGUAGE;
}

function t(key, lang) {
  const currentLang = lang || getStoredLanguage();
  return I18N_MESSAGES[currentLang]?.[key] || I18N_MESSAGES[DEFAULT_LANGUAGE]?.[key] || key;
}

function applyLanguage(lang) {
  const selected = I18N_MESSAGES[lang] ? lang : DEFAULT_LANGUAGE;
  try {
    localStorage.setItem('fishing_game_lang', selected);
  } catch (e) {}

  if (typeof document !== 'undefined') {
    document.documentElement.lang = selected;
    if (document.body) {
      document.body.dataset.lang = selected;
    }

    document.title = t('title', selected);

    const saveWarning = document.getElementById('saveWarning');
    if (saveWarning) {
      const text = saveWarning.querySelector('span');
      if (text) text.textContent = t('saveWarning', selected);
    }

    // Update text content
    document.querySelectorAll('[data-i18n]').forEach((node) => {
      const key = node.dataset.i18n;
      if (key) {
        node.textContent = t(key, selected);
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      const key = node.dataset.i18nPlaceholder;
      if (key) {
        node.placeholder = t(key, selected);
      }
    });

    // Update titles (tooltips)
    document.querySelectorAll('[data-i18n-title]').forEach((node) => {
      const key = node.dataset.i18nTitle;
      if (key) {
        node.title = t(key, selected);
      }
    });

    // Update select dropdown
    const select = document.getElementById('settingsLanguageSelect');
    if (select) select.value = selected;

    // Update language buttons active state
    document.querySelectorAll('.lang-btn[data-lang-code]').forEach((btn) => {
      if (btn.dataset.langCode === selected) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });
  }

  if (typeof window !== 'undefined') {
    window.currentLanguage = selected;
  }
  return selected;
}

