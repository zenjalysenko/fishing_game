function ensureLanguageSelectorUI() {
  if (typeof document === 'undefined') return;
  ensureLanguageStyles();

  const settingsModal = document.getElementById('settings');
  if (!settingsModal) return;

  // If already present, just make sure events are bound
  if (settingsModal.querySelector('.lang-switch-group') && document.getElementById('settingsLanguageSelect')) {
    bindLanguageEvents();
    return;
  }

  const windowEl = settingsModal.querySelector('.settings-window');
  if (!windowEl) return;

  // Create language selection block dynamically
  const langBlock = document.createElement('div');
  langBlock.className = 'settings-block';
  langBlock.id = 'injectedLanguageBlock';
  langBlock.innerHTML = `
    <h3 data-i18n="languageSectionTitle">🌐 Мова гри / Language</h3>
    <p class="muted" data-i18n="languageHint">Виберіть зручну мову для інтерфейсу, написів та меню:</p>
    <div class="lang-switch-group">
      <button type="button" class="lang-btn" data-lang-code="en" title="English">
        <span class="lang-flag">🇬🇧</span> <span class="lang-title">English</span>
      </button>
      <button type="button" class="lang-btn" data-lang-code="ru" title="Русский">
        <span class="lang-flag">🇷🇺</span> <span class="lang-title">Русский</span>
      </button>
      <button type="button" class="lang-btn" data-lang-code="uk" title="Українська">
        <span class="lang-flag">🇺🇦</span> <span class="lang-title">Українська</span>
      </button>
    </div>
    <div class="lang-select-wrapper">
      <label for="settingsLanguageSelect"><span data-i18n="quickSelect">Швидкий вибір зі списку:</span></label>
      <select id="settingsLanguageSelect" class="settings-lang-select" aria-label="Language selector">
        <option value="en">🇬🇧 English</option>
        <option value="ru">🇷🇺 Русский</option>
        <option value="uk">🇺🇦 Українська</option>
      </select>
    </div>
  `;

  const firstBlock = windowEl.querySelector('.settings-block');
  if (firstBlock) {
    windowEl.insertBefore(langBlock, firstBlock);
  } else {
    windowEl.appendChild(langBlock);
  }

  bindLanguageEvents();
  applyLanguage(getStoredLanguage());
}

function bindLanguageEvents() {
  if (typeof document === 'undefined') return;

  document.querySelectorAll('.lang-btn[data-lang-code]').forEach((btn) => {
    btn.onclick = () => {
      applyLanguage(btn.dataset.langCode);
    };
  });

  const select = document.getElementById('settingsLanguageSelect');
  if (select) {
    select.onchange = (e) => {
      applyLanguage(e.target.value);
    };
  }
}

const i18n = {
  t,
  applyLanguage,
  getLanguage: getStoredLanguage,
  bindLanguageEvents,
  ensureLanguageSelectorUI,
  ensureLanguageStyles,
  MESSAGES: I18N_MESSAGES
};

if (typeof window !== 'undefined') {
  window.i18n = i18n;
  window.t = t;
  window.ensureLanguageSelectorUI = ensureLanguageSelectorUI;
}

if (typeof document !== 'undefined') {
  function initI18n() {
    ensureLanguageStyles();
    ensureLanguageSelectorUI();
    applyLanguage(getStoredLanguage());
    bindLanguageEvents();
  }

  if (document.readyState === 'loading') {
    window.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    I18N_MESSAGES,
    DEFAULT_LANGUAGE,
    t,
    applyLanguage,
    getStoredLanguage,
    bindLanguageEvents,
    ensureLanguageSelectorUI,
    ensureLanguageStyles
  };
}
